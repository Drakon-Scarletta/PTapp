const TABLES = { de: DE, en: EN };
export const LANGS = [
  { id: 'de', label: 'Deutsch' },
  { id: 'en', label: 'English' }
];

let lang = 'de';

export function setLang(l) { lang = TABLES[l] ? l : 'de'; }
export function getLang() { return lang; }
export function locale() { return lang === 'en' ? 'en-GB' : 'de-AT'; }

export function detectLang() {
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'de';
  return nav.toLowerCase().startsWith('en') ? 'en' : 'de';
}

export function t(key, params) {
  let s = TABLES[lang][key];
  if (s == null) s = TABLES.de[key];
  if (s == null) return key;
  if (params) {
    Object.keys(params).forEach(k => { s = s.split('{' + k + '}').join(params[k]); });
  }
  return s;
}

// Zahl mit dem Dezimalzeichen der Sprache.
export function num(n) {
  return (Math.round(n * 10) / 10).toLocaleString(locale());
}

export function monthName(m) {
  return new Intl.DateTimeFormat(locale(), { month: 'long' }).format(new Date(2021, m, 1));
}

export function weekdayShort(i) {
  // i = 0 ist Montag.
  return new Intl.DateTimeFormat(locale(), { weekday: 'short' })
    .format(new Date(2021, 2, 1 + i));
}

export function longDate(d) {
  return d.toLocaleDateString(locale(), { weekday: 'long', day: 'numeric', month: 'long' });
}
