var TABLES = { de: DE, en: EN };
var LANGS = [
  { id: "de", label: "Deutsch" },
  { id: "en", label: "English" }
];
var lang = "de";
function setLang(l) {
  lang = TABLES[l] ? l : "de";
}
function getLang() {
  return lang;
}
function locale() {
  return lang === "en" ? "en-GB" : "de-AT";
}
function detectLang() {
  const nav = typeof navigator !== "undefined" && navigator.language || "de";
  return nav.toLowerCase().startsWith("en") ? "en" : "de";
}
function t(key, params) {
  let s = TABLES[lang][key];
  if (s == null) s = TABLES.de[key];
  if (s == null) return key;
  if (params) {
    Object.keys(params).forEach((k) => {
      s = s.split("{" + k + "}").join(params[k]);
    });
  }
  return s;
}
function num(n) {
  return (Math.round(n * 10) / 10).toLocaleString(locale());
}
function monthName(m) {
  return new Intl.DateTimeFormat(locale(), { month: "long" }).format(new Date(2021, m, 1));
}
function weekdayShort(i) {
  return new Intl.DateTimeFormat(locale(), { weekday: "short" }).format(new Date(2021, 2, 1 + i));
}
function longDate(d) {
  return d.toLocaleDateString(locale(), { weekday: "long", day: "numeric", month: "long" });
}

